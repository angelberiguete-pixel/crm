-- Family Power first-party, consent-gated website behavioral telemetry.
-- No IP addresses, cookies, fingerprint, form content, email, phone or raw URLs.
create table if not exists public.marketing_behavior_sites (
 id uuid primary key default gen_random_uuid(),
 tenant_id uuid not null references public.tenants(id) on delete cascade,
 hostname text not null unique check (hostname ~ '^[a-z0-9.-]{5,253}$'),
 display_name text not null check (length(display_name) between 2 and 100),
 enabled boolean not null default true,
 created_at timestamptz not null default now()
);
create index if not exists marketing_behavior_sites_tenant on public.marketing_behavior_sites(tenant_id);
alter table public.marketing_behavior_sites enable row level security;
revoke all on public.marketing_behavior_sites from public, anon, authenticated;
grant select on public.marketing_behavior_sites to authenticated;
drop policy if exists behavior_sites_tenant_read on public.marketing_behavior_sites;
create policy behavior_sites_tenant_read on public.marketing_behavior_sites
 for select to authenticated
 using (private.crm_is_tenant_admin(tenant_id) or private.crm_is_platform_admin());

insert into public.marketing_behavior_sites (tenant_id,hostname,display_name)
 select id,'family-power-v136-demo.vercel.app','Family Power · Sitio comercial'
 from public.tenants where slug='family-power'
on conflict (hostname) do nothing;

create table if not exists public.marketing_behavior_events (
 id bigint generated by default as identity primary key,
 tenant_id uuid not null references public.tenants(id) on delete cascade,
 site_id uuid not null references public.marketing_behavior_sites(id) on delete cascade,
 session_id uuid not null,
 event_name text not null check (event_name in (
  'page_view','click','scroll_depth','section_dwell','engaged_time',
  'form_start','form_submit','form_error','cta_whatsapp','cta_phone','page_exit'
 )),
 page_path text not null default '/' check (length(page_path) <= 120),
 section_key text check (length(section_key) <= 64),
 target_key text check (length(target_key) <= 64),
 device text not null default 'desktop' check (device in ('mobile','tablet','desktop')),
 country text check (country ~ '^[A-Z]{2}$'),
 utm_source text check (length(utm_source) <= 64),
 utm_medium text check (length(utm_medium) <= 64),
 utm_campaign text check (length(utm_campaign) <= 64),
 active_seconds numeric(9,2) check (active_seconds between 0 and 7200),
 scroll_percent smallint check (scroll_percent between 0 and 100),
 x_percent smallint check (x_percent between 0 and 100),
 y_percent smallint check (y_percent between 0 and 100),
 created_at timestamptz not null default now()
);
create index if not exists marketing_behavior_events_tenant_time
 on public.marketing_behavior_events(tenant_id,created_at desc);
create index if not exists marketing_behavior_events_site_session
 on public.marketing_behavior_events(site_id,session_id,created_at desc);
alter table public.marketing_behavior_events enable row level security;
revoke all on public.marketing_behavior_events from public,anon,authenticated;
grant select,insert,delete on public.marketing_behavior_events to service_role;
revoke all on sequence public.marketing_behavior_events_id_seq from public,anon,authenticated;
grant usage,select on sequence public.marketing_behavior_events_id_seq to service_role;

-- Event ingestion must use the secure server-side Edge Function only.
-- Enforce actual tenant provenance even when invoked with service role.
create or replace function private.validate_behavior_site_tenant()
returns trigger language plpgsql set search_path = '' as $$
begin
 if not exists(select 1 from public.marketing_behavior_sites s
   where s.id=new.site_id and s.tenant_id=new.tenant_id and s.enabled)
 then
  raise exception 'Invalid site-to-tenant binding' using errcode='42501';
 end if;
 return new;
end;
$$;
drop trigger if exists check_behavior_site_tenant on public.marketing_behavior_events;
create trigger check_behavior_site_tenant before insert or update
 on public.marketing_behavior_events for each row
 execute function private.validate_behavior_site_tenant();

create or replace function public.marketing_behavior_overview(
 p_tenant_id uuid, p_days integer default 30
)
returns jsonb language plpgsql stable security definer
set search_path='' as $$
declare res jsonb;
begin
 if auth.uid() is null or not (
  private.crm_is_tenant_admin(p_tenant_id) or private.crm_is_platform_admin()
 ) then raise exception 'Not permitted' using errcode='42501'; end if;
 if p_days not in (7,30,90) then
  raise exception 'Invalid date range' using errcode='22023'; end if;
 with e as (
  select * from public.marketing_behavior_events
  where tenant_id=p_tenant_id and created_at>=now() - make_interval(days=>p_days)
 )
 select pg_catalog.jsonb_build_object(
 'tenant_id', p_tenant_id,
 'days',p_days,
 'connected',exists(select 1 from public.marketing_behavior_sites
   where tenant_id=p_tenant_id and enabled),
 'sites',(select coalesce(pg_catalog.jsonb_agg(
   pg_catalog.jsonb_build_object('name',s.display_name,'host',s.hostname)
   order by s.display_name),'[]'::jsonb)
   from public.marketing_behavior_sites s where s.tenant_id=p_tenant_id and s.enabled),
 'summary',pg_catalog.jsonb_build_object(
   'sessions',(select count(distinct session_id) from e),
   'pageviews',(select count(*) from e where event_name='page_view'),
   'clicks',(select count(*) from e where event_name in ('click','cta_whatsapp','cta_phone')),
   'whatsapp_clicks',(select count(*) from e where event_name='cta_whatsapp'),
   'forms_started',(select count(distinct session_id) from e where event_name='form_start'),
   'forms_submitted',(select count(distinct session_id) from e where event_name='form_submit'),
   'avg_active_seconds',(select coalesce(round(avg(total),1),0)
     from (select sum(active_seconds) total from e where event_name='engaged_time'
       group by session_id) x),
   'avg_scroll_percent',(select coalesce(round(avg(deep),0),0)
     from (select max(scroll_percent) deep from e where event_name='scroll_depth'
      group by session_id) x)
 ),
 'daily',(select coalesce(pg_catalog.jsonb_agg(
   pg_catalog.jsonb_build_object('day',x.d::text,'visits',x.visits,'views',x.views)
   order by x.d),'[]'::jsonb)
   from (select created_at::date d,
     count(distinct session_id) visits,
     count(*) filter(where event_name='page_view') views
     from e group by 1 order by 1) x),
 'section_dwell',(select coalesce(pg_catalog.jsonb_agg(
    pg_catalog.jsonb_build_object('section',x.section_key,'seconds',x.seconds,'visits',x.sessions)
    order by x.seconds desc),'[]'::jsonb)
    from (select section_key,round(sum(active_seconds),0) seconds,
      count(distinct session_id) sessions
      from e where event_name='section_dwell' and section_key is not null
      group by section_key order by seconds desc limit 10) x),
 'click_targets',(select coalesce(pg_catalog.jsonb_agg(
    pg_catalog.jsonb_build_object('target',x.target_key,'count',x.n)
    order by x.n desc),'[]'::jsonb)
    from (select coalesce(target_key,'sin_etiqueta') target_key,count(*) n
      from e where event_name in ('click','cta_whatsapp','cta_phone')
      group by 1 order by n desc limit 10) x),
 'countries',(select coalesce(pg_catalog.jsonb_agg(
    pg_catalog.jsonb_build_object('country',x.country,'sessions',x.n)
    order by x.n desc),'[]'::jsonb)
    from (select coalesce(country,'ND') country,count(distinct session_id) n
      from e group by 1 order by n desc limit 10) x),
 'devices',(select coalesce(pg_catalog.jsonb_agg(
    pg_catalog.jsonb_build_object('device',x.device,'sessions',x.n)
    order by x.n desc),'[]'::jsonb)
    from (select device,count(distinct session_id) n from e
      group by device order by n desc) x),
 'sources',(select coalesce(pg_catalog.jsonb_agg(
    pg_catalog.jsonb_build_object('source',x.source,'sessions',x.n)
    order by x.n desc),'[]'::jsonb)
    from (select coalesce(utm_source,'directo') source,count(distinct session_id) n from e
      group by 1 order by n desc limit 10) x),
 'scroll_depth',(select coalesce(pg_catalog.jsonb_agg(
    pg_catalog.jsonb_build_object('depth',x.scroll_percent,'count',x.n)
    order by x.scroll_percent),'[]'::jsonb)
    from (select scroll_percent,count(distinct session_id) n from e
      where event_name='scroll_depth' and scroll_percent is not null
      group by scroll_percent order by scroll_percent) x),
 'click_positions',(select coalesce(pg_catalog.jsonb_agg(
    pg_catalog.jsonb_build_object('x',x.x,'y',x.y,'count',x.n)
    order by x.n desc),'[]'::jsonb)
    from (select (round(x_percent/10.0)*10)::int x,
      (round(y_percent/10.0)*10)::int y,count(*) n from e
      where x_percent is not null and y_percent is not null
      group by 1,2 order by n desc limit 120) x)
 ) into res;
 return res;
end;
$$;
revoke all on function public.marketing_behavior_overview(uuid,integer)
 from public,anon,authenticated;
grant execute on function public.marketing_behavior_overview(uuid,integer)
 to authenticated;
comment on function public.marketing_behavior_overview(uuid,integer) is
 'Aggregated consented website interactions, accessible only to the active company administrators or platform admins. No personal identifiers or fingerprint profiles.';
